class MiningError(RuntimeError):
    """A deterministic mining invariant failed."""


class MergeTreeOperationalError(MiningError):
    """The exact merge-tree invocation returned neither clean nor conflict."""

    def __init__(self, result: Any):
        self.returncode = int(result.returncode)
        self.stdout = bytes(result.stdout)
        self.stderr = bytes(result.stderr)
        super().__init__(
            f"merge-tree returned operational status {self.returncode}: "
            f"{decode_git_text(self.stderr).strip()}"
        )


class RepositoryLock:
    """An OS-backed single-writer lock released even if a process is killed."""

    def __init__(self, output_root: Path, slug: str):
        self.path = output_root / "_locks" / f"{slug}.lock"
        self.handle: Any = None

    def __enter__(self) -> "RepositoryLock":
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.handle = self.path.open("a+b")
        self.handle.seek(0, os.SEEK_END)
        if self.handle.tell() == 0:
            self.handle.write(b"\0")
            self.handle.flush()
        self.handle.seek(0)
        try:
            if os.name == "nt":
                import msvcrt

                msvcrt.locking(self.handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl

                fcntl.flock(self.handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as error:
            self.handle.close()
            self.handle = None
            raise MiningError(
                f"{self.path.stem}: another miner holds the repository output lock"
            ) from error
        return self

    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> None:
        if self.handle is None:
            return
        with contextlib.suppress(OSError):
            self.handle.seek(0)
            if os.name == "nt":
                import msvcrt

                msvcrt.locking(self.handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                import fcntl

                fcntl.flock(self.handle.fileno(), fcntl.LOCK_UN)
        self.handle.close()
        self.handle = None
        with contextlib.suppress(OSError):
            self.path.unlink()


