def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def decode_git_text(value: bytes) -> str:
    return value.decode("utf-8", errors="replace")


def decode_git_path(value: bytes) -> str:
    # ensure_ascii=True serializes surrogate escapes safely and reversibly.
    return value.decode("utf-8", errors="surrogateescape")


def encode_git_path(value: str) -> bytes:
    return value.encode("utf-8", errors="surrogateescape")


def deterministic_git_environment() -> dict[str, str]:
    environment = dict(os.environ)
    for key in list(environment):
        if key in SCRUBBED_GIT_ENVIRONMENT_KEYS or key.startswith(
            SCRUBBED_GIT_ENVIRONMENT_PREFIXES
        ):
            environment.pop(key, None)
    environment.update(DETERMINISTIC_GIT_ENVIRONMENT_OVERRIDES)
    return environment


