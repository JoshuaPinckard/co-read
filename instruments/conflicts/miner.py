@dataclasses.dataclass(frozen=True)
class GitResult:
    args: tuple[str, ...]
    returncode: int
    stdout: bytes
    stderr: bytes


class GitRepository:
    def __init__(self, path: Path):
        self.path = path.resolve()
        self.environment = deterministic_git_environment()

    def command(self, arguments: Sequence[str]) -> list[str]:
        return [
            "git",
            *GIT_CONFIG_ARGS,
            "-C",
            str(self.path),
            *arguments,
        ]

    def run(
        self,
        arguments: Sequence[str],
        *,
        check: bool = True,
        input_bytes: bytes | None = None,
    ) -> GitResult:
        completed = subprocess.run(
            self.command(arguments),
            input=input_bytes,
            capture_output=True,
            env=self.environment,
            check=False,
        )
        result = GitResult(
            args=tuple(arguments),
            returncode=completed.returncode,
            stdout=completed.stdout,
            stderr=completed.stderr,
        )
        if check and result.returncode != 0:
            stderr = decode_git_text(result.stderr).strip()
            raise MiningError(
                f"git {' '.join(arguments)} failed with {result.returncode}: {stderr}"
            )
        return result

    def text(self, arguments: Sequence[str]) -> str:
        return decode_git_text(self.run(arguments).stdout).strip()


def is_reparse_point(path: Path) -> bool:
    attributes = getattr(path.lstat(), "st_file_attributes", 0)
    return bool(attributes & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0))


def validate_task_mirror(
    mirror_root: Path,
    slug: str,
    repository_spec: dict[str, Any],
) -> tuple[Path, GitRepository, dict[str, Any]]:
    if not SLUG_RE.fullmatch(slug):
        raise MiningError(f"unsafe repository slug {slug!r}")
    if not mirror_root.is_dir():
        raise MiningError(f"mirror root is absent or not a directory: {mirror_root}")
    if mirror_root.is_symlink() or is_reparse_point(mirror_root):
        raise MiningError(
            f"mirror root must not be a symlink or reparse point: {mirror_root}"
        )
    root = mirror_root.resolve(strict=True)
    candidate = root / slug
    if not candidate.is_dir():
        raise MiningError(f"{slug}: missing task-owned mirror {candidate}")
    if candidate.is_symlink() or is_reparse_point(candidate):
        raise MiningError(f"{slug}: task mirror must not be a symlink or reparse point")
    resolved = candidate.resolve(strict=True)
    if resolved.parent != root:
        raise MiningError(f"{slug}: task mirror escapes the declared mirror root")
    alternates = resolved / "objects" / "info" / "alternates"
    if alternates.exists() and alternates.read_bytes().strip():
        raise MiningError(f"{slug}: task mirror has nonempty object alternates")

    repository = GitRepository(resolved)
    if repository.text(["rev-parse", "--is-bare-repository"]) != "true":
        raise MiningError(f"{slug}: mirror is not bare")
    if repository.text(["rev-parse", "--is-shallow-repository"]) != "false":
        raise MiningError(f"{slug}: shallow history would truncate the merge population")
    origin = repository.text(["config", "--get", "remote.origin.url"])
    expected_origin = str(repository_spec.get("url", ""))
    if not expected_origin or origin != expected_origin:
        raise MiningError(
            f"{slug}: mirror origin {origin!r} != manifest origin {expected_origin!r}"
        )
    promisor = repository.text(["config", "--get", "remote.origin.promisor"])
    partial_filter = repository.text(
        ["config", "--get", "remote.origin.partialclonefilter"]
    )
    if promisor != "true" or partial_filter != "blob:none":
        raise MiningError(
            f"{slug}: mirror is not the required promisor blob:none partial mirror"
        )
    return resolved, repository, {
        "alternates": False,
        "bare": True,
        "direct_child": True,
        "origin": origin,
        "partial_clone_filter": partial_filter,
        "promisor": True,
        "reparse_point": False,
        "shallow": False,
    }


def read_nul_field(stream: Any) -> bytes:
    field = bytearray()
    while True:
        chunk = stream.read(1)
        if not chunk:
            raise MiningError("NUL-framed cat-file stream ended before a terminator")
        if chunk == b"\0":
            return bytes(field)
        field.extend(chunk)


class BatchCatFile:
    """Long-lived cat-file process for commit/blob reads."""

    def __init__(self, repository: GitRepository):
        self.repository = repository
        self.process: subprocess.Popen[bytes] | None = None
        self.cache: dict[bytes, tuple[str, str, bytes] | None] = {}

    def __enter__(self) -> "BatchCatFile":
        self.process = subprocess.Popen(
            self.repository.command(["cat-file", "--batch", "-Z"]),
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=self.repository.environment,
        )
        return self

    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> None:
        if self.process is None:
            return
        if self.process.stdin:
            self.process.stdin.close()
        try:
            self.process.wait(timeout=30)
        except subprocess.TimeoutExpired:
            self.process.kill()
            self.process.wait()
        if exc_type is None and self.process.returncode not in (0, None):
            stderr = b"" if self.process.stderr is None else self.process.stderr.read()
            raise MiningError(
                f"git cat-file --batch failed: {decode_git_text(stderr).strip()}"
            )

    def get_with_oid(
        self, specification: bytes | str
    ) -> tuple[str, str, bytes] | None:
        if isinstance(specification, str):
            key = specification.encode("ascii")
        else:
            key = specification
        if key in self.cache:
            return self.cache[key]
        if b"\0" in key:
            self.cache[key] = None
            return None
        if self.process is None or self.process.stdin is None or self.process.stdout is None:
            raise MiningError("cat-file batch process is not running")
        self.process.stdin.write(key + b"\0")
        self.process.stdin.flush()
        header = read_nul_field(self.process.stdout)
        if header.endswith(b" missing"):
            self.cache[key] = None
            return None
        try:
            oid_raw, object_type, size_raw = header.rsplit(b" ", 2)
            size = int(size_raw)
        except (ValueError, TypeError) as error:
            raise MiningError(f"invalid cat-file header: {header!r}") from error
        payload = self.process.stdout.read(size)
        terminator = self.process.stdout.read(1)
        if len(payload) != size or terminator != b"\0":
            raise MiningError("truncated cat-file batch payload")
        answer = (
            oid_raw.decode("ascii"),
            object_type.decode("ascii"),
            payload,
        )
        self.cache[key] = answer
        return answer

    def get(self, specification: bytes | str) -> tuple[str, bytes] | None:
        answer = self.get_with_oid(specification)
        if answer is None:
            return None
        return answer[1], answer[2]


@dataclasses.dataclass
class Hunk:
    old_start: int
    old_count: int
    new_start: int
    new_count: int


